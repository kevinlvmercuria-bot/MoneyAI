CREATE TABLE IF NOT EXISTS members(id varchar(5) PRIMARY KEY,profile jsonb NOT NULL);
CREATE TABLE IF NOT EXISTS tasks(
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,member_id varchar(5) NOT NULL REFERENCES members(id),
 goal varchar(10) NOT NULL CHECK(goal IN ('general','wake','balance','launch')),
 status varchar(20) NOT NULL CHECK(status IN ('pending_review','approved','rejected','executed_simulated')),
 strategy varchar(30) NOT NULL,priority integer NOT NULL,message varchar(1000) NOT NULL,reason varchar(400) NOT NULL,
 edited_message varchar(1000) NOT NULL DEFAULT '',scenario varchar(10),context_json jsonb,
 CHECK((status='executed_simulated' AND scenario IS NOT NULL AND scenario IN ('noReply','reply','booking','visit'))
   OR(status<>'executed_simulated' AND scenario IS NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS tasks_effectivemember ON tasks(member_id) WHERE status IN ('pending_review','approved');
CREATE TABLE IF NOT EXISTS operationlogs(
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name varchar(40) NOT NULL,description varchar(400) NOT NULL,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS carerecords(
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,member_id varchar(5) NOT NULL REFERENCES members(id),
 outcome varchar(20) NOT NULL CHECK(outcome IN ('已沟通','未回复','暂不联系','推荐不合适','不再营销')),
 note varchar(1000) NOT NULL,owner varchar(80) NOT NULL,follow_up date,recorded_as_of date NOT NULL,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS carerecords_member ON carerecords(member_id,id DESC);
CREATE TABLE IF NOT EXISTS products(id varchar(40) PRIMARY KEY,profile jsonb NOT NULL);
CREATE TABLE IF NOT EXISTS sourcerecords(
 source_table varchar(40) NOT NULL,source_id varchar(100) NOT NULL,member_id varchar(5),payload jsonb NOT NULL,
 PRIMARY KEY(source_table,source_id)
);
CREATE INDEX IF NOT EXISTS sourcerecords_member ON sourcerecords(member_id,source_table);
CREATE TABLE IF NOT EXISTS importruns(source_hash char(64) PRIMARY KEY,imported_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,counts_json jsonb NOT NULL);
CREATE TABLE IF NOT EXISTS memberprofilebackups(
 source_hash char(64) NOT NULL,member_id varchar(5) NOT NULL,profile jsonb NOT NULL,
 backed_up_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,PRIMARY KEY(source_hash,member_id)
);
CREATE TABLE IF NOT EXISTS memberimportstage(id varchar(5) PRIMARY KEY,profile jsonb NOT NULL);
CREATE TABLE IF NOT EXISTS productimages(
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,product_id varchar(40) NOT NULL,content_type varchar(30) NOT NULL,
 image_data bytea NOT NULL,created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS productimages_product ON productimages(product_id,id DESC);
CREATE TABLE IF NOT EXISTS copydrafts(
 id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,member_id varchar(5) NOT NULL REFERENCES members(id),
 model varchar(100) NOT NULL,message varchar(1000) NOT NULL,original_message varchar(1000) NOT NULL,
 reason varchar(500) NOT NULL,product_ids jsonb NOT NULL,context_json jsonb,
 created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,copied_at timestamptz
);
CREATE TABLE IF NOT EXISTS membernoteedits(
 note_id varchar(100) PRIMARY KEY,member_id varchar(5) NOT NULL REFERENCES members(id),note_type varchar(20) NOT NULL,
 note_text varchar(1200) NOT NULL,is_pinned boolean NOT NULL DEFAULT false,author_name varchar(80) NOT NULL,
 updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
